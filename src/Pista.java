
public class Pista {

    private String nomePista;
    private int tamanho;

    public Pista(String nomePista, int tamanho) {
        this.nomePista = nomePista;
        this.tamanho = tamanho;
    }

    public String getNomePista() {
        return nomePista;
    }

    public int getTamanho() {
        return tamanho;
    }
}
